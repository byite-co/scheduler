-- AI 검사 한도 재산정 — 가격 인상 + 결제 수수료 + 검사 방식 변경 반영.
--
-- [왜 다시 하는가] 20260807020000 의 한도(월 70회 · 280장)는 두 전제가 모두 깨졌다.
--   1) 매출 전제: 2,900원 **결제액**의 30% = 870원.
--      · 가격이 8,900 / 학생당 4,900 으로 올랐다.
--      · 그런데 결제액은 우리 돈이 아니다 — 부가세와 스토어·PG 수수료를 빼야 한다.
--        옛 계산은 이걸 빼지 않아서 실제 예산을 과대평가하고 있었다.
--   2) 원가 전제: 프롬프트 936토큰 · 사진 1장 1,600토큰.
--      지금은 관찰 프롬프트(2,892토큰) + 4분할·10% 겹침(사진 1장 = 1,568px 조각 4장)이라
--      **사진 1장 원가가 약 3.5배**가 됐다. 실측 약 15.2원/장.
--
-- [실수령액] 스토어·PG 는 부가세를 뺀 금액에 수수료를 매긴다.
--   · 학생 프리미엄 8,900 → ÷1.1 = 8,091 → ×0.85(앱스토어 15%) = **6,877원**
--   · 과외쌤 학생당 4,900 → ÷1.1 = 4,455 → ×0.97(웹 PG 3%)   = **4,321원**
--
-- [예산은 둘 중 낮은 쪽] 한도는 요청자(requested_by) 1인 기준의 단일 값이다.
--   같은 학생이 과외쌤 결제로도, 본인 프리미엄으로도 검사를 부를 수 있다.
--   낮은 쪽(과외쌤 경로)에 맞춰야 두 경로 모두 안전하다.
--     예산 = 4,321 × 30% = **1,296원/월**
--   (학생 프리미엄 경로는 같은 한도에서 예산의 18% 만 쓴다 — 여유가 있다.)
--
-- [원가 — Haiku 4.5 · 관찰 프롬프트 · 4분할+겹침, 입력 $1/Mtok · 출력 $5/Mtok · 1,370원/$]
--   · 호출 1회 고정분: 2,892(프롬프트) + 130×5(출력) = 3,542µ$ ≈ 4.9원
--   · 사진 1장:        4조각 × 1,600 = 6,400µ$        ≈ 8.8원
--   · 1장짜리 호출 ≈ 13.6원 (실측 15.2원 — 출력이 더 길었다. 아래는 실측 쪽으로 보정한다)
--
-- [새 한도] 월 70회·280장을 그대로 두면 최악 2,795원으로 예산의 216% 다. 다시 잡는다.
--     ai_check_max_attempts_per_month : 70 → **40**
--     ai_check_max_photos_per_month   : 280 → **100**
--   · 최악 조합(40회·100장) = 216 + 980 = 1,196원 → 예산의 92% ✅
--   · 정상 사용(30회·90장)  = 162 +  882 = 1,044원 → 예산의 81%
--   · 전부 1장(40회·40장)   = 216 +  392 =   608원 → 47%
--
-- ⚠️ **이 방식은 경제적으로 아슬아슬하다.** 정상적으로 많이 쓰는 학생 한 명이 이미 예산의
--    81% 를 쓴다. 옛 한도가 목표하던 "정상 사용의 2배 여유"는 15.2원/장 에서는 살 수 없다.
--    한도를 더 주고 싶으면 원가를 낮추는 것 말고 방법이 없다.
--
-- [Gemini 로 바꾸면] 실험에서 분할 없이 장당 0.6원으로 같은 정확도가 나왔다
--   (Flash-Lite $0.30/$2.50, 사진 1장 1,064토큰 상한).
--     · 호출 1.6원 + 사진 0.4원 → 옛 한도(70회·280장)도 237원, 예산의 **18%** 다.
--   즉 모델을 바꾸면 이 축소는 되돌릴 수 있고 오히려 더 늘릴 수 있다.
--
-- [왜 지금은 Haiku 기준으로 정하는가]
--   1) 지금 **실제로 도는 것**이 Haiku + 4분할이다. Gemini 는 실험이고 제품 코드에 없다.
--      돌지 않는 모델 기준으로 한도를 주면 첫 사용자가 그대로 예산을 넘긴다.
--   2) 방향이 안전하다. 나중에 Gemini 로 바꿔 한도를 **올리는** 것은 좋은 변화지만,
--      280장에 익숙해진 사용자에게서 100장으로 줄이는 것은 나쁜 변화다.
--   모델이 확정되면 이 파일의 계산을 그대로 뒤집어 상수 두 개만 바꾸면 된다.

